#!/usr/bin/env node
/* Builds data/kb-pack.js (window.AREX_KB_PACK) from data/Forex_Strategy_Knowledge_Base.md.  Usage: node scripts/build-kb.js */
const fs = require('fs'), path = require('path'), kb = require('../js/core/kb.js');
const src = path.join(__dirname, '..', 'data', 'Forex_Strategy_Knowledge_Base.md'), md = fs.readFileSync(src, 'utf8');
const pack = kb.parse(md, { builtAt: new Date().toISOString().slice(0, 10) });
fs.writeFileSync(path.join(__dirname, '..', 'data', 'kb-pack.js'), '/* generated by scripts/build-kb.js — do not edit */\nwindow.AREX_KB_PACK=' + JSON.stringify(pack) + ';\n');
console.log('chunks:', pack.chunks.length, '| conflicts:', pack.chunks.filter(c => c.conflictId).length, '| images:', Object.keys(pack.images).length);
